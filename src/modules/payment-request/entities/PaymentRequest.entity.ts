import { Entity, Column, ManyToOne, JoinColumn, Index } from "typeorm";
import { BaseEntity } from "../../../shared/entities/BaseEntity";
import { Projects } from "../../project/entities/Project.entity";
import { Tasks } from "../../task/entities/Task.entity";
import { Users } from "../../user/entities/User.entity";
import { Vendors } from "../../vendor/entities/Vendor.entity";

export const numericColumnTransformer = {
    to: (data: number | null | undefined) => data,
    from: (data: string | null | undefined) => (data == null ? null : Math.round(Number(data)))
};

export enum PaymentRequestType {
    PROJECT = "PROJECT",
    OTHER_WORK = "OTHER_WORK",
    ADVANCE = "ADVANCE"
}

export enum PaymentRequestApprovalStatus {
    DRAFT = "DRAFT",
    PENDING_REVIEWER = "PENDING_REVIEWER",
    NEED_MORE_DOCS = "NEED_MORE_DOCS",
    PENDING_BOD = "PENDING_BOD",
    APPROVED = "APPROVED",
    REJECTED = "REJECTED",
    CANCELLED = "CANCELLED"
}

export enum PaymentDueStatus {
    WAITING = "WAITING",
    DUE_SOON = "DUE_SOON",
    OVERDUE = "OVERDUE",
    PARTIALLY_PAID = "PARTIALLY_PAID", // Đã chi một phần
    PAID = "PAID",
    NOT_APPLICABLE = "NOT_APPLICABLE"
}

export enum PaymentSettlementStatus {
    NOT_APPLICABLE = "NOT_APPLICABLE", // Phiếu thường
    PENDING = "PENDING",               // Đang xin tạm ứng, chưa chi đủ 100%
    WAITING_SETTLEMENT = "WAITING_SETTLEMENT", // Đã chi đủ 100% tiền ứng, chờ nhân sự nộp chứng từ
    SETTLEMENT_SUBMITTED = "SETTLEMENT_SUBMITTED", // Đã nộp chứng từ quyết toán, chờ duyệt
    SETTLED = "SETTLED"                // Đã quyết toán hoàn tất
}

export interface PaymentTransactionRecord {
    id: string; // crypto.randomUUID()
    amount: number; // Số tiền chi đợt này (nguyên VNĐ)
    paidAt: string;
    payerId: string;
    payerName?: string;
    paymentMethod: string;
    cashVoucherInfo?: { voucherNo?: string; notes?: string };
    proofFiles: PaymentRequestFile[];
    note?: string;
}

export enum PaymentMethod {
    BANK_TRANSFER = "BANK_TRANSFER",
    CASH = "CASH"
}

export interface CashVoucherInfo {
    voucherNo?: string;
    bookNo?: string;
    receiverName?: string;
    receiverAddress?: string;
    reason?: string;
    amount?: number;
    amountInWords?: string;
    debitAccount?: string;
    creditAccount?: string;
    attachmentCount?: number;
    createdDate?: string;
    companyName?: string;
    companyAddress?: string;
}

export interface PaymentRequestFile {
    name: string;
    url: string;
    type?: string;
    fileType?: string;
    docType?: string;
    size?: number;
    round?: number;
    uploadedAt?: string;
}

export interface PaymentRequestHistoryEntry {
    action: "CREATED" | "SUBMITTED" | "SUPPLEMENTED" | "REVIEWED" | "BOD_DECISION" | "PAID" | "CANCELLED"
        | "PAID_INSTALLMENT" | "SUBMIT_SETTLEMENT" | "APPROVE_SETTLEMENT" | "REJECT_SETTLEMENT";
    at: string;
    byId: string;
    byName?: string | null;
    note?: string | null;
    snapshot?: {
        content: string;
        amount: number;
        dueDate: string | Date;
        invoiceImages: PaymentRequestFile[];
        invoicePdfs: PaymentRequestFile[];
        settlementDueDate?: string | Date | null;
        overBudgetReason?: string | null;
    };
}

@Entity()
@Index(["approvalStatus", "dueDate"])
@Index(["projectId", "approvalStatus"])
export class PaymentRequests extends BaseEntity {

    @Column({
        type: "enum",
        enum: PaymentRequestType
    })
    type: PaymentRequestType;

    @Column({ type: "text" })
    content: string;

    @Column({ type: "decimal", precision: 15, scale: 3 })
    amount: number;

    @Column({ type: "date" })
    dueDate: Date;

    @Column({ type: "date", nullable: true })
    confirmedDueDate: Date | null;

    @Column({ type: "varchar", length: 26, nullable: true })
    confirmedDueDateById: string | null;

    @ManyToOne(() => Users, { nullable: true })
    @JoinColumn({ name: "confirmedDueDateById" })
    confirmedDueDateBy: Users | null;

    @Index()
    @Column({ type: "varchar", length: 26, nullable: true })
    projectId: string | null;

    @ManyToOne(() => Projects, { nullable: true })
    @JoinColumn({ name: "projectId" })
    project: Projects | null;

    @Index()
    @Column({ type: "varchar", length: 26, nullable: true })
    taskId: string | null;

    @ManyToOne(() => Tasks, { nullable: true })
    @JoinColumn({ name: "taskId" })
    task: Tasks | null;

    // Vendor thực hiện công việc (chỉ có giá trị với type = PROJECT khi task được giao cho vendor)
    @Column({ type: "varchar", length: 26, nullable: true })
    vendorId: string | null;

    @ManyToOne(() => Vendors, { nullable: true })
    @JoinColumn({ name: "vendorId" })
    vendor: Vendors | null;

    // true nếu do hệ thống tự tạo (VD: khi phân công task cho vendor), false nếu người dùng tự tạo
    @Column({ type: "boolean", default: false })
    isAutoGenerated: boolean;

    @Column({ type: "jsonb", default: [] })
    history: PaymentRequestHistoryEntry[];

    @Column({ type: "decimal", precision: 15, scale: 3, nullable: true })
    costPrice: number | null;

    @Column({ type: "jsonb", default: [] })
    invoiceImages: PaymentRequestFile[];

    @Column({ type: "jsonb", default: [] })
    invoicePdfs: PaymentRequestFile[];

    @Column({ type: "boolean", default: false })
    isUrgent: boolean;

    @Column({ type: "varchar", length: 50, nullable: true })
    expenseCategory: string | null;

    @Index()
    @Column({ type: "varchar", length: 26 })
    requesterId: string;

    @ManyToOne(() => Users)
    @JoinColumn({ name: "requesterId" })
    requester: Users;

    @Index()
    @Column({
        type: "enum",
        enum: PaymentRequestApprovalStatus,
        default: PaymentRequestApprovalStatus.DRAFT
    })
    approvalStatus: PaymentRequestApprovalStatus;

    @Column({ type: "varchar", length: 26, nullable: true })
    reviewerId: string | null;

    @ManyToOne(() => Users, { nullable: true })
    @JoinColumn({ name: "reviewerId" })
    reviewer: Users | null;

    @Column({ type: "timestamptz", nullable: true })
    reviewedAt: Date | null;

    @Column({ type: "text", nullable: true })
    reviewNote: string | null;

    @Column({ type: "varchar", length: 26, nullable: true })
    submittedToBodById: string | null;

    @ManyToOne(() => Users, { nullable: true })
    @JoinColumn({ name: "submittedToBodById" })
    submittedToBodBy: Users | null;

    @Column({ type: "timestamptz", nullable: true })
    submittedToBodAt: Date | null;

    @Column({ type: "varchar", length: 26, nullable: true })
    bodDecisionById: string | null;

    @ManyToOne(() => Users, { nullable: true })
    @JoinColumn({ name: "bodDecisionById" })
    bodDecisionBy: Users | null;

    @Column({ type: "timestamptz", nullable: true })
    bodDecisionAt: Date | null;

    @Column({ type: "text", nullable: true })
    bodDecisionReason: string | null;

    @Index()
    @Column({
        type: "enum",
        enum: PaymentDueStatus,
        default: PaymentDueStatus.WAITING
    })
    paymentStatus: PaymentDueStatus;

    @Column({ type: "timestamptz", nullable: true })
    paidAt: Date | null;

    @Column({
        type: "enum",
        enum: PaymentMethod,
        nullable: true
    })
    paymentMethod: PaymentMethod | null;

    @Column({ type: "jsonb", nullable: true })
    cashVoucherInfo: CashVoucherInfo | null;

    @Column({ type: "jsonb", default: [] })
    paymentProofs: PaymentRequestFile[];

    // Theo dõi chi tiền từng đợt
    @Column({ type: "numeric", precision: 15, scale: 0, default: 0, transformer: numericColumnTransformer })
    paidAmount: number;

    @Column({ type: "jsonb", default: [] })
    paymentTransactions: PaymentTransactionRecord[];

    // Vòng đời Tạm ứng & Quyết toán hoàn ứng
    @Column({
        type: "enum",
        enum: PaymentSettlementStatus,
        default: PaymentSettlementStatus.NOT_APPLICABLE
    })
    settlementStatus: PaymentSettlementStatus;

    @Column({ type: "numeric", precision: 15, scale: 0, nullable: true, transformer: numericColumnTransformer })
    settledAmount: number | null;

    /**
     * Quy ước dấu của settlementDifference:
     * Dương (> 0): Thực chi vượt tạm ứng -> Công ty chi bù cho nhân sự
     * Âm (< 0): Thực chi ít hơn tạm ứng -> Nhân sự phải nộp lại tiền thừa về công ty
     * Bằng 0: Khớp 100% số tiền tạm ứng
     */
    @Column({ type: "numeric", precision: 15, scale: 0, nullable: true, transformer: numericColumnTransformer })
    settlementDifference: number | null;

    @Column({ type: "date", nullable: true })
    settlementDueDate: Date | null;

    @Column({ type: "jsonb", default: [] })
    settlementFiles: PaymentRequestFile[];

    @Column({ type: "text", nullable: true })
    settlementNote: string | null;

    // Xác nhận đã thu hồi tiền thừa (nếu diff < 0) hoặc đã chi bù (nếu diff > 0)
    @Column({ type: "boolean", default: false })
    settlementRefundConfirmed: boolean;

    @Column({ type: "text", nullable: true })
    overBudgetReason: string | null;
}
